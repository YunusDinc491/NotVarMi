using Microsoft.EntityFrameworkCore;

namespace NotVarMi.Api.Data;

public static class PostgresBootstrap
{
    // EnsureCreated checks every schema in the database, including unrelated service tables.
    // Create only our own schema when none of our tables exist; never modify partial/existing tables.
    public static void Initialize(NotesDbContext db, bool seedExamples)
    {
        using var transaction = db.Database.BeginTransaction();
        db.Database.ExecuteSqlRaw("SELECT pg_advisory_xact_lock(718093546203)");
        var count = db.Database.SqlQueryRaw<int>("""
            SELECT COUNT(*)::int AS "Value"
            FROM pg_catalog.pg_class c
            JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'notvarmi'
              AND c.relname IN ('Courses', 'Files', 'Notebooks', 'DataProtectionKeys', 'CourseNotebooks')
              AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
            """).Single();
        if (count == 0)
        {
            db.Database.ExecuteSqlRaw(db.Database.GenerateCreateScript());
            if (seedExamples)
            {
                db.Courses.AddRange(new Course { Name = "Heat Transfer" }, new Course { Name = "Fluid Mechanics" });
                db.SaveChanges();
            }
        }
        else if (count != 4 && count != 5)
        {
            throw new InvalidOperationException("NotVarMı veritabanı şeması eksik. Mevcut verileri korumak için otomatik değişiklik yapılmadı.");
        }
        else if (count == 4)
        {
            db.Database.ExecuteSqlRaw("""
                CREATE TABLE notvarmi."CourseNotebooks" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "CourseId" integer NOT NULL REFERENCES notvarmi."Courses" ("Id") ON DELETE CASCADE,
                    "Name" character varying(150) NOT NULL,
                    "Html" text NOT NULL,
                    "Css" text NOT NULL,
                    "Javascript" text NOT NULL,
                    "Version" integer NOT NULL DEFAULT 0
                )
                """);
            db.Database.ExecuteSqlRaw("CREATE INDEX \"IX_CourseNotebooks_CourseId\" ON notvarmi.\"CourseNotebooks\" (\"CourseId\")");
        }
        var hasContentFlag = db.Database.SqlQueryRaw<bool>("""
            SELECT EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = 'notvarmi' AND table_name = 'Files' AND column_name = 'IsContent'
            ) AS "Value"
            """).Single();
        if (!hasContentFlag)
            db.Database.ExecuteSqlRaw("ALTER TABLE notvarmi.\"Files\" ADD COLUMN \"IsContent\" boolean NOT NULL DEFAULT FALSE");
        db.Database.ExecuteSqlRaw("ALTER TABLE notvarmi.\"Courses\" ADD COLUMN IF NOT EXISTS \"Instructor\" character varying(100) NOT NULL DEFAULT ''");
        db.Database.ExecuteSqlRaw("CREATE TABLE IF NOT EXISTS notvarmi.\"NotebookSeedSuppressions\" (\"CourseId\" integer NOT NULL REFERENCES notvarmi.\"Courses\" (\"Id\") ON DELETE CASCADE, \"Name\" character varying(150) NOT NULL, PRIMARY KEY (\"CourseId\", \"Name\"))");
        transaction.Commit();
    }
}
